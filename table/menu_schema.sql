-- Menu schema for PostgreSQL
-- reception_id is BIGINT in every table.
-- No foreign-key constraints are defined, as requested.
-- Surrogate IDs use BIGINT IDENTITY.
-- MenuID and ItemID are application identifiers and use BIGINT.

CREATE TABLE IF NOT EXISTS reception_menu (
    reception_id BIGINT PRIMARY KEY,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_updated_at
    ON reception_menu(updated_at);

-- Menu entries from MenuStruct.Menus
CREATE TABLE IF NOT EXISTS reception_menu_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reception_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    menu_id BIGINT NOT NULL,
    menu_name TEXT NOT NULL,
    price INTEGER NOT NULL DEFAULT 0,
    prepaid_price INTEGER NOT NULL DEFAULT 0,
    need_skill TEXT,
    need_facility TEXT,
    specify_name_flag BOOLEAN NOT NULL DEFAULT FALSE,
    spend_minute INTEGER,
    for_book_type INTEGER
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_item_reception_id
    ON reception_menu_item(reception_id);
CREATE INDEX IF NOT EXISTS idx_reception_menu_item_menu_id
    ON reception_menu_item(reception_id, menu_id);

COMMENT ON COLUMN reception_menu_item.sort_order IS 'Original position in MenuStruct.Menus';
COMMENT ON COLUMN reception_menu_item.for_book_type IS '1 = book only, 2 = book and at shop';

-- Menu.Items: list of item IDs belonging to a menu
CREATE TABLE IF NOT EXISTS reception_menu_item_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    item_id BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_item_content_menu_item_id
    ON reception_menu_item_content(menu_item_id);

-- Menu.PaidOptions: []ItemOption
CREATE TABLE IF NOT EXISTS reception_menu_paid_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    item_id BIGINT NOT NULL,
    price INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_paid_option_menu_item_id
    ON reception_menu_paid_option(menu_item_id);

-- Menu.FreeOptions: [][]int. Each group is one inner []int.
CREATE TABLE IF NOT EXISTS reception_menu_free_option_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_free_option_group_menu_item_id
    ON reception_menu_free_option_group(menu_item_id);

CREATE TABLE IF NOT EXISTS reception_menu_free_option_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    free_option_group_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    item_id BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_free_option_item_group_id
    ON reception_menu_free_option_item(free_option_group_id);

-- Menu.FreeMultiOptions: []int
CREATE TABLE IF NOT EXISTS reception_menu_free_multi_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    item_id BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_free_multi_option_menu_item_id
    ON reception_menu_free_multi_option(menu_item_id);

-- ItemDetails from MenuStruct.ItemDetails
CREATE TABLE IF NOT EXISTS reception_menu_item_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reception_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    item_id BIGINT NOT NULL,
    item_name TEXT NOT NULL,
    img_path TEXT
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_item_detail_reception_id
    ON reception_menu_item_detail(reception_id);
CREATE INDEX IF NOT EXISTS idx_reception_menu_item_detail_item_id
    ON reception_menu_item_detail(reception_id, item_id);

COMMENT ON COLUMN reception_menu_item_detail.img_path IS 'Image path saved by common.ImgSave';

-- ItemDetail.Choices: [][]string. Each group is one inner []string.
CREATE TABLE IF NOT EXISTS reception_menu_item_detail_choice_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_detail_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_item_detail_choice_group_detail_id
    ON reception_menu_item_detail_choice_group(item_detail_id);

CREATE TABLE IF NOT EXISTS reception_menu_item_detail_choice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    choice_group_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    choice_text TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reception_menu_item_detail_choice_group_id
    ON reception_menu_item_detail_choice(choice_group_id);

COMMENT ON TABLE reception_menu IS 'One menu document per reception; stores MenuStruct metadata';
COMMENT ON TABLE reception_menu_item IS 'MenuStruct.Menus entries';
COMMENT ON TABLE reception_menu_item_content IS 'Ordered item IDs in Menu.Items';
COMMENT ON TABLE reception_menu_paid_option IS 'Menu.PaidOptions entries';
COMMENT ON TABLE reception_menu_free_option_group IS 'Outer groups in Menu.FreeOptions';
COMMENT ON TABLE reception_menu_free_option_item IS 'Item IDs within each Menu.FreeOptions group';
COMMENT ON TABLE reception_menu_free_multi_option IS 'Menu.FreeMultiOptions entries';
COMMENT ON TABLE reception_menu_item_detail IS 'MenuStruct.ItemDetails entries';
COMMENT ON TABLE reception_menu_item_detail_choice_group IS 'Outer groups in ItemDetail.Choices';
COMMENT ON TABLE reception_menu_item_detail_choice IS 'Choice strings within each ItemDetail.Choices group';
