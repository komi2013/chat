  -- menu_schema.sql
-- PostgreSQL schema for collection.MenuStruct, Menu, ItemDetail and ItemOption.
-- Assumptions:
--   * reception_id identifies one menu document.
--   * menu_id is unique within a reception, not globally.
--   * item_id is unique within a reception's itemDetails.
--   * sort_order preserves the order of Go slices.
--   * Foreign keys are used between these menu tables; reception_id intentionally
--     has no FK because the reception schema's key/type must be confirmed together.

BEGIN;

CREATE TABLE IF NOT EXISTS menu (
    reception_id VARCHAR(255) PRIMARY KEY,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS menu_item (
    reception_id       VARCHAR(255) NOT NULL,
    menu_id            INTEGER NOT NULL,
    sort_order         INTEGER NOT NULL DEFAULT 0,
    menu_name          TEXT NOT NULL DEFAULT '',
    price              INTEGER NOT NULL DEFAULT 0,
    prepaid_price      INTEGER NOT NULL DEFAULT 0,
    need_skill         TEXT,
    need_facility      TEXT,
    specify_name_flag  BOOLEAN NOT NULL DEFAULT FALSE,
    spend_minute       INTEGER NOT NULL DEFAULT 0,
    for_book_type      INTEGER NOT NULL DEFAULT 0,
    items              INTEGER[] NOT NULL DEFAULT '{}',
    free_multi_options INTEGER[] NOT NULL DEFAULT '{}',
    PRIMARY KEY (reception_id, menu_id),
    UNIQUE (reception_id, sort_order),
    FOREIGN KEY (reception_id) REFERENCES menu(reception_id) ON DELETE CASCADE
);

-- PaidOptions: []ItemOption
CREATE TABLE IF NOT EXISTS menu_paid_option (
    reception_id VARCHAR(255) NOT NULL,
    menu_id      INTEGER NOT NULL,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    item_id      INTEGER NOT NULL,
    price        INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (reception_id, menu_id, sort_order),
    FOREIGN KEY (reception_id, menu_id)
        REFERENCES menu_item(reception_id, menu_id) ON DELETE CASCADE
);

-- FreeOptions: [][]int. One row per group; the values array preserves
-- the order of item IDs within each group.
CREATE TABLE IF NOT EXISTS menu_free_option_group (
    reception_id VARCHAR(255) NOT NULL,
    menu_id      INTEGER NOT NULL,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    item_ids     INTEGER[] NOT NULL DEFAULT '{}',
    PRIMARY KEY (reception_id, menu_id, sort_order),
    FOREIGN KEY (reception_id, menu_id)
        REFERENCES menu_item(reception_id, menu_id) ON DELETE CASCADE
);

-- ItemDetails: []ItemDetail
CREATE TABLE IF NOT EXISTS menu_item_detail (
    reception_id VARCHAR(255) NOT NULL,
    item_id      INTEGER NOT NULL,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    item_name    TEXT NOT NULL DEFAULT '',
    img_path     TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (reception_id, item_id),
    UNIQUE (reception_id, sort_order),
    FOREIGN KEY (reception_id) REFERENCES menu(reception_id) ON DELETE CASCADE
);

-- Choices: [][]string. One row per choice group.
CREATE TABLE IF NOT EXISTS menu_item_choice_group (
    reception_id VARCHAR(255) NOT NULL,
    item_id      INTEGER NOT NULL,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (reception_id, item_id, sort_order),
    FOREIGN KEY (reception_id, item_id)
        REFERENCES menu_item_detail(reception_id, item_id) ON DELETE CASCADE
);

-- One row per choice in a group, preserving the order of each []string.
CREATE TABLE IF NOT EXISTS menu_item_choice (
    reception_id VARCHAR(255) NOT NULL,
    item_id      INTEGER NOT NULL,
    group_order  INTEGER NOT NULL,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    choice_value TEXT NOT NULL,
    PRIMARY KEY (reception_id, item_id, group_order, sort_order),
    FOREIGN KEY (reception_id, item_id, group_order)
        REFERENCES menu_item_choice_group(reception_id, item_id, sort_order)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_menu_item_reception_id
    ON menu_item (reception_id);
CREATE INDEX IF NOT EXISTS idx_menu_paid_option_menu
    ON menu_paid_option (reception_id, menu_id);
CREATE INDEX IF NOT EXISTS idx_menu_free_option_group_menu
    ON menu_free_option_group (reception_id, menu_id);
CREATE INDEX IF NOT EXISTS idx_menu_item_detail_reception_id
    ON menu_item_detail (reception_id);
CREATE INDEX IF NOT EXISTS idx_menu_item_choice_group_item
    ON menu_item_choice_group (reception_id, item_id);
CREATE INDEX IF NOT EXISTS idx_menu_item_choice_group
    ON menu_item_choice (reception_id, item_id, group_order);

COMMIT;


