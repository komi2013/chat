-- Reception schema migrated from collection.ReceptionStruct.
-- External-key constraints are intentionally omitted.
-- reception_id remains VARCHAR because ReceptionStruct.ReceptionID is a string.
-- channel_id is BIGINT. Sequence-generated row IDs are BIGINT IDENTITY.

CREATE TABLE IF NOT EXISTS reception (
    reception_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL,
    admin_names TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    join_names TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    inquiry_names TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    subscriptions TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    order_user_ids BIGINT[] NOT NULL DEFAULT ARRAY[]::BIGINT[],
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    reception_title VARCHAR(255),
    skills TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    work_staff_need BOOLEAN NOT NULL DEFAULT FALSE
);

COMMENT ON TABLE reception IS 'Reception master and scalar-array settings';
COMMENT ON COLUMN reception.channel_id IS 'Channel ID; BIGINT, without a foreign-key constraint';
COMMENT ON COLUMN reception.admin_names IS 'Admin alias names';
COMMENT ON COLUMN reception.join_names IS 'Joined alias names';
COMMENT ON COLUMN reception.inquiry_names IS 'Inquiry alias names';
COMMENT ON COLUMN reception.order_user_ids IS 'User IDs associated with orders; stored as text to match the source []string';

CREATE INDEX idx_reception_channel_id ON reception(channel_id);

